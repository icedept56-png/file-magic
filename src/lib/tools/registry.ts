export function getTool(id: string): ToolDef | undefined {
  return TOOLS.find((t) => t.id === id);
}

export function filterTools(query: string, category: string): ToolDef[] {
  const q = query.trim().toLowerCase();
  return TOOLS.filter((t) => {
    if (category !== "all" && t.category !== category) return false;
    if (!q) return true;
    return (
      t.name.toLowerCase().includes(q) ||
      t.nameEn.toLowerCase().includes(q) ||
      t.desc.toLowerCase().includes(q) ||
      (t.descEn?.toLowerCase().includes(q) ?? false) ||
      t.id.includes(q) ||
      (t.keywords?.some((k) => k.includes(q) || q.includes(k)) ?? false)
    );
  });
}

export const TOOL_COUNT = TOOLS.length;

/** true when the tool opens its own full-screen editor view */
export function isEditorTool(id: string): boolean {
  return EDITOR_IDS.includes(id);
}
